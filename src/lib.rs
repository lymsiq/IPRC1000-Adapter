//! 纯规则层 —— **无 Windows 依赖、无全局状态、无 IO**。
//!
//! ## 为什么要单独一层
//!
//! 2026-11-01 之前，全部逻辑都在 `bin` 里，且混着注册表/驱动/音频调用，
//! 于是"按住语音键 1.2 秒后松动会怎样"这种问题**只能靠真机试**。
//! 当晚 6 个 bug 全部是这么发现的，其中 3 个属于"推理不出来、只能撞"。
//!
//! 这一层只放**能纯函数化**的规则：给定输入 → 给定输出，不碰系统。
//! 规则搬进来之后就能写单测，也就有了"改完之后至少这些不会退"的保证。
//!
//! 约定：本层**不许**使用 `crate::backend`、`windows`、`std::fs`、`Mutex`。
//! 新增逻辑前先问一句：它能不能写成"输入 → 输出"？能就放这里。

